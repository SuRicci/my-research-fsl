                assert abs(null-old).max()<1e-10 and np.array_equal(null.argmax(-1),old.argmax(-1))
                sc=torch.cat([predict(n,p) for n in nets]).numpy();assert np.isfinite(sc).all()
                pred.append(sc.argmax(-1).astype(np.uint8));identity.append(null.argmax(-1).astype(np.uint8))
