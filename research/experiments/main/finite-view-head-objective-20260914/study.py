def train(data):
    choices={}
    for ds in CFG['domains']:
        tr=prepare_source(data,ds,'train');va=prepare_source(data,ds,'selection')
        for seed in CFG['seeds']:
            rng=np.random.RandomState(seed);order=np.concatenate([rng.permutation(len(tr)) for _ in range(CFG['updates']*CFG['batch']//len(tr))]).reshape(CFG['updates'],CFG['batch'])
            np.save(OUT/f'{ds}_{seed}_order.npy',order)
            for arm in ARMS:
                guard();torch.manual_seed(seed);net=Map();opt=torch.optim.Adam(net.parameters(),lr=CFG['lr'],weight_decay=CFG['weight_decay'])
                key=f'{ds}_{seed}_{arm}';rows=[];best=None;state=None;start=time.time()
                for step in range(CFG['updates']+1):
                    if step:
                        ids=order[step-1];sc=predict(net,tr.get(ids));loss=objective(sc,arm)
                        assert torch.isfinite(loss);opt.zero_grad();loss.backward()
                        assert all(torch.isfinite(p.grad).all() for p in net.parameters());opt.step()
                    if step in CFG['checkpoints']:
                        guard();sc=torch.from_numpy(batched(net,va));ce=losses(sc);pred=sc.argmax(-1)
                        correct=int((pred==torch.tensor(Y)).sum());mean=float(ce.mean());rank=(correct,-mean,-step)
                        f=f'checkpoints/{key}_{step}.npz';np.savez_compressed(OUT/f,predictions=pred.numpy().astype(np.uint8),query_ce=ce.numpy())
                        rows.append({'step':step,'correct':correct,'ce':mean,'path':str(OUT/f)})
                        if best is None or rank>best[0]:best=(rank,rows[-1]);state=copy.deepcopy(net.state_dict())
                mp=OUT/'models'/f'{key}.pt';torch.save(state,mp)
                choices[key]={'source':ds,'seed':seed,'arm':arm,'step':best[1]['step'],'history':rows,'path':str(mp),'sha256':sha(mp),'seconds':time.time()-start}
                dump('training_progress.json',choices);print('FIT_COMPLETE',key,'step',best[1]['step'],'seconds',round(time.time()-start,2),flush=True)
        tr.record();va.record();del tr,va
    dump('selection_lock.json',choices);return choices
